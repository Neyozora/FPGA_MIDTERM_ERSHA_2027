"""
Milestone 2: verify the model's tensor shapes, parameter count and size on a
real batch of preprocessed Fashion-MNIST images, on CPU and (if available) GPU.

Outputs:
    reports/model/model_summary.md
    reports/model/model_summary.json

Usage (from the repository root, inside the venv):
    python -m sw.model.summary
"""
import json
import platform
import sys

import numpy as np
import torch

from sw.config import CLASS_NAMES, REPORTS_DIR, SEED
from sw.data.dataset import load_processed
from sw.data.preprocess import int8_to_float
from sw.model.cnn import SHAPES, FashionCNN, expected_macs, expected_param_counts

REPORT_DIR = REPORTS_DIR / "model"
BATCH = 64


def main() -> int:
    torch.manual_seed(SEED)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)

    # ---- real input batch from the processed dataset ------------------------
    d = load_processed()
    x_np = int8_to_float(d["x_test"][:BATCH])[:, None, :, :]   # [N,28,28] -> [N,1,28,28]
    x = torch.from_numpy(x_np)
    assert x.dtype == torch.float32 and tuple(x.shape) == (BATCH, 1, 28, 28)

    model = FashionCNN().eval()

    # ---- shapes -----------------------------------------------------------
    with torch.no_grad():
        inter = model.forward_intermediates(x)
        logits = model(x)
    shape_rows = []
    for name, t in inter.items():
        got = tuple(t.shape[1:])
        ok = got == SHAPES[name]
        shape_rows.append((name, list(t.shape), int(np.prod(got)), ok))
        print(f"{name:6s} {str(list(t.shape)):20s} elems/sample={np.prod(got):6d} {'OK' if ok else 'MISMATCH'}")
    assert all(r[3] for r in shape_rows)
    assert torch.equal(logits, inter["fc"]), "forward() and forward_intermediates() disagree"

    # ---- parameters ---------------------------------------------------------
    exp_p = expected_param_counts()
    got_p = {n: p.numel() for n, p in model.named_parameters()}
    assert got_p == dict(exp_p), (got_p, exp_p)
    n_params = sum(got_p.values())
    n_weights = sum(v for k, v in got_p.items() if k.endswith("weight"))
    n_biases = n_params - n_weights
    size = {
        "fp32_bytes": n_params * 4,
        "int8_weights_int32_bias_bytes": n_weights * 1 + n_biases * 4,
    }
    macs = expected_macs()
    print(f"parameters: {n_params} ({n_weights} weights + {n_biases} biases)")
    print(f"size: FP32 {size['fp32_bytes']} B, INT8/INT32 {size['int8_weights_int32_bias_bytes']} B")
    print(f"MACs/image: {sum(macs.values())}")

    # ---- CPU vs GPU ---------------------------------------------------------
    gpu = {"available": torch.cuda.is_available()}
    if gpu["available"]:
        dev = torch.device("cuda")
        m_gpu = FashionCNN().to(dev).eval()
        m_gpu.load_state_dict(model.state_dict())
        with torch.no_grad():
            logits_gpu = m_gpu(x.to(dev)).cpu()
        gpu.update(name=torch.cuda.get_device_name(0),
                   capability=".".join(map(str, torch.cuda.get_device_capability(0))),
                   max_abs_diff_vs_cpu=float((logits_gpu - logits).abs().max()))
        print(f"GPU {gpu['name']} (sm_{gpu['capability']}): max |logits_gpu - logits_cpu| = "
              f"{gpu['max_abs_diff_vs_cpu']:.3e}")
        assert gpu["max_abs_diff_vs_cpu"] < 1e-4

    env = {"python": platform.python_version(), "torch": torch.__version__,
           "cuda_runtime": torch.version.cuda, "cudnn": torch.backends.cudnn.version()}

    summary = {"shapes": {r[0]: r[1] for r in shape_rows}, "params": got_p,
               "total_params": n_params, "size": size, "macs": dict(macs),
               "total_macs": sum(macs.values()), "gpu": gpu, "env": env,
               "note": "Untrained model (random init, seed %d); this report verifies structure only." % SEED}
    (REPORT_DIR / "model_summary.json").write_text(json.dumps(summary, indent=2))

    L = ["# Model Summary (Milestone 2)", "",
         "Generated by `python -m sw.model.summary`. The model is **untrained**: this report checks",
         "structure (shapes, parameters, size) only, not accuracy.", "",
         f"Environment: Python {env['python']}, PyTorch {env['torch']}, CUDA runtime {env['cuda_runtime']}, "
         f"cuDNN {env['cudnn']}", "",
         f"## Intermediate tensor shapes (real test batch, N = {BATCH})", "",
         "| Tensor | Shape (N,C,H,W) | Elements / image | Matches spec |", "|---|---|---|---|"]
    L += [f"| {n} | {s} | {e:,} | {'yes' if ok else '**NO**'} |" for n, s, e, ok in shape_rows]
    L += ["", "## Parameters", "", "| Tensor | PyTorch shape | Count |", "|---|---|---|"]
    L += [f"| {n} | {list(p.shape)} | {p.numel():,} |" for n, p in model.named_parameters()]
    L += [f"| **Total** | | **{n_params:,}** |", "",
          "## Model size", "", "| Representation | Bytes |", "|---|---|",
          f"| FP32 (all parameters x 4 B) | {size['fp32_bytes']:,} |",
          f"| INT8 weights + INT32 biases (hardware) | {size['int8_weights_int32_bias_bytes']:,} |", "",
          "## MACs per image", "", "| Layer | MACs |", "|---|---|"]
    L += [f"| {k} | {v:,} |" for k, v in macs.items()]
    L += [f"| **Total** | **{sum(macs.values()):,}** |", "", "## GPU check", ""]
    if gpu["available"]:
        L += [f"- Device: {gpu['name']} (compute capability {gpu['capability']})",
              f"- Max absolute logit difference GPU vs CPU (same weights, same batch): "
              f"{gpu['max_abs_diff_vs_cpu']:.3e}"]
    else:
        L += ["- CUDA not available; GPU check skipped."]
    L += ["", f"Classes: {', '.join(f'{i}={c}' for i, c in enumerate(CLASS_NAMES))}", ""]
    (REPORT_DIR / "model_summary.md").write_text("\n".join(L), encoding="utf-8")
    print(f"report written to {REPORT_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
